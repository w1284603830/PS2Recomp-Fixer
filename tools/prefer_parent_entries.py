"""Finds dispatch-table slots that point at a jump-table fragment (entry_XXXXXX) although the enclosing recompiled
function can be entered at the same address, and writes them as overrides (RUNTIME_PATCHES row 123).

Usage: python -I prefer_parent_entries.py <runner dir> <out header> [--report N]

Background: the jump-table scan (scan_jump_tables.py, dod_upstream20.toml) adds entry labels for switch targets, and
the recompiler emits each as a small function besides the function that already contains the code (with a goto
label and, for resumable addresses, a case in its entry switch). The dispatch table maps the address to the small
fragment, whose branches out of its few instructions all return to the scheduler. A loop entered there hops from
fragment to fragment through the scheduler instead of running on gotos inside the enclosing function. Dispatching
to the enclosing function runs the very same guest instructions from the same address.

A slot is overridden when the fragment's address is a case of the entry switch of a function whose
"// Address: a - b" range contains it (the largest such function).
"""
import re
import sys
from pathlib import Path

CASE = re.compile(r'^\s*case 0x([0-9a-fA-F]+)u: goto label_')
ADDR = re.compile(r'^// Address: 0x([0-9a-fA-F]+) - 0x([0-9a-fA-F]+)')
DEF = re.compile(r'^void (\w+)\(uint8_t\* rdram, R5900Context\* ctx, PS2Runtime \*runtime\) \{')
SLOT = re.compile(r'g_ps2RecompiledFunctionTable\[(\d+)\] = (\w+); // 0x([0-9a-fA-F]+)')


def scan_function(path):
    name, lo, hi, cases = None, None, None, set()
    in_switch = False
    with open(path, encoding='utf-8', errors='replace') as f:
        for n, line in enumerate(f):
            if lo is None:
                m = ADDR.match(line)
                if m:
                    lo, hi = int(m.group(1), 16), int(m.group(2), 16)
                    continue
            if name is None:
                m = DEF.match(line)
                if m:
                    name = m.group(1)
                continue
            if 'switch (ctx->pc) {' in line:
                in_switch = True
                continue
            if in_switch:
                m = CASE.match(line)
                if m:
                    cases.add(int(m.group(1), 16))
                    continue
                break
            if n > 40 and not in_switch:
                break
    return name, lo, hi, cases


def main():
    runner = Path(sys.argv[1])
    out = Path(sys.argv[2])
    report = int(sys.argv[sys.argv.index('--report') + 1]) if '--report' in sys.argv else 0
    funcs = {}
    for path in runner.glob('*.cpp'):
        if not (path.name.startswith('FUN_') or path.name.startswith('entry_') or path.name.startswith('caseD_')):
            continue
        name, lo, hi, cases = scan_function(path)
        if name and lo is not None:
            funcs[name] = (lo, hi, cases)
    slots = []
    for line in (runner / 'register_functions.cpp').read_text(encoding='utf-8', errors='replace').splitlines():
        m = SLOT.search(line)
        if m:
            slots.append((int(m.group(1)), m.group(2), int(m.group(3), 16)))
    # Functions that can be entered at an address, by address.
    enterable = {}
    for name, (lo, hi, cases) in funcs.items():
        for a in cases:
            if lo <= a < hi:
                enterable.setdefault(a, []).append((hi - lo, name))
    overrides = []
    for slot, fn, addr in slots:
        if not fn.startswith('entry_'):
            continue
        parents = [p for p in enterable.get(addr, []) if p[1] != fn and not p[1].startswith('entry_')]
        if parents:
            size, parent = max(parents)
            overrides.append((slot, addr, fn, parent))
    lines = ['// Generated by tools/scripts/prefer_parent_entries.py (RUNTIME_PATCHES row 123): dispatch-table slots',
             '// that go to the enclosing function instead of a jump-table fragment at the same address.',
             '// {slot, address, enclosing function}']
    for slot, addr, fn, parent in sorted(overrides, key=lambda o: o[1]):
        lines.append(f'DOD_PREFER_PARENT({slot}, 0x{addr:06X}, {parent}) // was {fn}')
    out.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    frag_slots = sum(1 for _, fn, _ in slots if fn.startswith('entry_'))
    print(f'{len(funcs)} functions scanned, {len(slots)} slots, {frag_slots} go to entry_ fragments, '
          f'{len(overrides)} overridden to the enclosing function -> {out}')
    for o in sorted(overrides, key=lambda o: o[1])[:report]:
        print(f'  slot {o[0]} 0x{o[1]:06X}: {o[2]} -> {o[3]}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
